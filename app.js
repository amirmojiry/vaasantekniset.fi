let currentLang = "en";

function applyLanguage(lang) {
  currentLang = lang;
  document.documentElement.lang = lang;
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.dataset.i18n;
    const value = translations[lang][key];
    if (value) el.textContent = value;
  });
  document.querySelector(".lang-switch").textContent = lang === "en" ? "FI" : "EN";
}

function makeMailto(subject, body) {
  return `mailto:${CONTACT_EMAIL}?subject=${encodeURIComponent(subject)}&body=${encodeURIComponent(body)}`;
}

document.querySelectorAll(".contact-email-text").forEach((el) => {
  el.textContent = CONTACT_EMAIL;
});

document.querySelector(".job-mail-link").href = makeMailto(
  "Open application – Vaasa Tekniset",
  "Hello Vaasa Tekniset,\n\nI would like to submit an open application.\n\nName:\nField / expertise:\nPhone:\n\nShort introduction:\n\nI will attach my CV to this email.\n"
);

document.getElementById("contactForm").addEventListener("submit", (event) => {
  event.preventDefault();
  const data = new FormData(event.currentTarget);
  const subject = `Service enquiry – ${data.get("service")}`;
  const body = [
    "Hello Vaasa Tekniset,",
    "",
    `Name: ${data.get("name")}`,
    `Email: ${data.get("email")}`,
    `Service: ${data.get("service")}`,
    "",
    "Message:",
    data.get("message"),
    ""
  ].join("\n");
  window.location.href = makeMailto(subject, body);
});

document.querySelectorAll("[data-service]").forEach((link) => {
  link.addEventListener("click", () => {
    const select = document.querySelector('select[name="service"]');
    const service = link.dataset.service;
    if ([...select.options].some((o) => o.value === service)) select.value = service;
  });
});

document.querySelector(".lang-switch").addEventListener("click", () => {
  applyLanguage(currentLang === "en" ? "fi" : "en");
});

const navToggle = document.querySelector(".nav-toggle");
const nav = document.querySelector(".main-nav");
navToggle.addEventListener("click", () => {
  const open = nav.classList.toggle("open");
  navToggle.setAttribute("aria-expanded", String(open));
});
nav.querySelectorAll("a").forEach((link) => link.addEventListener("click", () => {
  nav.classList.remove("open");
  navToggle.setAttribute("aria-expanded", "false");
}));

